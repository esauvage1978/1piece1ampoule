/** Génère les champs i18n à partir du français si absents */
export function withI18n(row) {
  const langs = ['en', 'de', 'it', 'es'];
  const out = { ...row };
  for (const lang of langs) {
    for (const field of ['title', 'symptom', 'cause', 'solution', 'tools', 'safety_warning']) {
      const k = `${field}_${lang}`;
      const fr = `${field}_fr`;
      if (out[fr] && (out[k] === undefined || out[k] === null || out[k] === '')) {
        out[k] = out[fr];
      }
    }
  }
  return out;
}

